/* Pre-generates the level decks and writes levels-data.js.
   One level per restaurant theme — all hard, all identical difficulty.
   Run: node tools/generate-levels.js */
"use strict";
const fs = require("fs");
const path = require("path");

const THEMES = [
  { name: "Sushi Bar", emoji: "🍣", items: ["🍣", "🍙", "🍱", "🍤", "🥟", "🍥", "🍘", "🐙", "🦐", "🍢"] },
  { name: "Taco Stand", emoji: "🌮", items: ["🌮", "🌯", "🥙", "🥗", "🌽", "🍟", "🍗", "🫘", "🧀", "🥑"] },
  { name: "Pizza Parlor", emoji: "🍕", items: ["🍕", "🍝", "🥖", "🍗", "🥗", "🍟", "🥨", "🍦", "🍪", "🥤"] },
  { name: "Ramen House", emoji: "🍜", items: ["🍜", "🥟", "🍤", "🍗", "🍛", "🍚", "🍥", "🍵", "🥚", "🍘"] }
];

// identical hard difficulty on every level: full menu, demands up to 10,
// long shift (45 to serve), tight patience
function levelCfg(level) {
  return {
    menuItems: 8, // each shift works from 8 dishes, picked from the theme's 10
    target: 60, // longer shift — 60 happy customers, 62 in the book
    patience: 70, // 2x patience — blind-dealing kitchen needs the slack
    beltSpeed: 70, // a touch slower — draws each shift out
    refillMs: 1900,
    maxOnBelt: 40, // roomier belt — surplus food has somewhere to sit,
    qtyMax: 10
  };
}

// mulberry32 — small, deterministic
function mulberry32(seed) {
  let a = seed >>> 0;
  return function () {
    a |= 0; a = (a + 0x6D2B79F5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

const levels = [];
for (let level = 1; level <= THEMES.length; level++) {
  const cfg = levelCfg(level);
  const rng = mulberry32(20250501 + level * 7919);
  // the shift's menu: 8 of the theme's 10 dishes (seeded pick — the same 8 every load)
  const themeItems = THEMES[level - 1].items;
  const menu = [...themeItems].sort(() => rng() - 0.5).slice(0, 8);
  const roster = [];
  for (let i = 0; i < cfg.target + 2; i++) {
    // demand is 5..10 — every order is a feast, shifts run long
    roster.push([menu[Math.floor(rng() * menu.length)], 5 + Math.floor(rng() * (cfg.qtyMax - 4))]);
  }
  // kitchen deck: same multiset of plates, but grouped into cooking batches of 3-5 same-type
  // plates (never a lonely single), then the batches themselves are shuffled. So the line
  // shows runs of the same dish scattered across the menu — not perfectly aligned to orders.
  const byType = new Map();
  roster.forEach((c, src) => {
    if (!byType.has(c[0])) byType.set(c[0], []);
    for (let i = 0; i < c[1]; i++) byType.get(c[0]).push(src); // one plate per ordered dish
  });
  const batches = [];
  for (const srcs of byType.values()) {
    for (let i = 0; i < srcs.length; ) {
      let n = Math.min(3 + Math.floor(rng() * 3), srcs.length - i);
      if (i + n === srcs.length - 1) n += 1; // never leave a lonely single as the tail (max batch 6)
      batches.push(srcs.slice(i, i + n));
      i += n;
    }
  }
  for (let i = batches.length - 1; i > 0; i--) {
    const j = Math.floor(rng() * (i + 1));
    [batches[i], batches[j]] = [batches[j], batches[i]];
  }
  const pool = batches.flat();
  levels.push({ ...cfg, menu, roster, pool });
}

const out = "/* Auto-generated by tools/generate-levels.js — do not edit by hand. */\n" +
  "globalThis.BELT_BITE_LEVELS = " + JSON.stringify(levels, null, 1) + ";\n";
fs.writeFileSync(path.join(__dirname, "..", "levels-data.js"), out);
console.log("wrote levels-data.js with", levels.length, "levels,", levels[0].roster.length, "customers each");