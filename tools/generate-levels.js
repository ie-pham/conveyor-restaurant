/* Pre-generates the level decks and writes levels-data.js.
   One level per restaurant theme — all hard, all identical difficulty.
   Run: node tools/generate-levels.js */
"use strict";
const fs = require("fs");
const path = require("path");

const THEMES = [
  { name: "Sushi Bar", emoji: "🍣", items: ["🍣", "🍙", "🍱", "🍤", "🥟", "🍥", "🍘", "🐙", "🦐", "🍢"] },
  { name: "Taco Stand", emoji: "🌮", items: ["🌮", "🌯", "🥙", "🥗", "🌽", "🍟", "🍗", "🫘", "🧀", "🥑"] },
  { name: "Pizza Parlor", emoji: "🍕", items: ["🍕", "🍝", "🥖", "🍗", "🥗", "🍟", "🥨", "🍦", "🍪", "🥤"] },
  { name: "Ramen House", emoji: "🍜", items: ["🍜", "🥟", "🍤", "🍗", "🍛", "🍚", "🍥", "🍵", "🥚", "🍘"] }
];

// identical hard difficulty on every level: full menu, demands up to 10,
// long shift (45 to serve), tight patience
function levelCfg(level) {
  return {
    menuItems: 10,
    target: 45,
    patience: 25,
    beltSpeed: 165,
    refillMs: 1900,
    maxOnBelt: 13,
    qtyMax: 10
  };
}

// mulberry32 — small, deterministic
function mulberry32(seed) {
  let a = seed >>> 0;
  return function () {
    a |= 0; a = (a + 0x6D2B79F5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

const levels = [];
for (let level = 1; level <= THEMES.length; level++) {
  const cfg = levelCfg(level);
  const rng = mulberry32(20250501 + level * 7919);
  const menu = THEMES[level - 1].items;
  const roster = [];
  for (let i = 0; i < cfg.target + 2; i++) {
    roster.push([menu[Math.floor(rng() * menu.length)], 1 + Math.floor(rng() * cfg.qtyMax)]);
  }
  levels.push({ ...cfg, roster });
}

const out = "/* Auto-generated by tools/generate-levels.js — do not edit by hand. */\n" +
  "globalThis.BELT_BITE_LEVELS = " + JSON.stringify(levels, null, 1) + ";\n";
fs.writeFileSync(path.join(__dirname, "..", "levels-data.js"), out);
console.log("wrote levels-data.js with", levels.length, "levels,", levels[0].roster.length, "customers each");