/* Pre-generates the 50 deterministic level decks and writes levels-data.js.
   Run: node tools/generate-levels.js
   Seeded PRNG -> regenerating always produces the same decks. */
"use strict";
const fs = require("fs");
const path = require("path");

const THEMES = [
  { name: "Sushi Bar", emoji: "🍣", items: ["🍣", "🍙", "🍱", "🍤", "🥟", "🍥", "🍘", "🍚", "🦐", "🥢"] },
  { name: "Taco Stand", emoji: "🌮", items: ["🌮", "🌯", "🥑", "🫓", "🧀", "🌶️", "🍖", "🍗", "🫘", "🌽"] },
  { name: "Pizza Parlor", emoji: "🍕", items: ["🍕", "🍅", "🧀", "🫒", "🍄", "🥓", "🌶️", "🥬", "🍖", "🥖"] },
  { name: "Ramen House", emoji: "🍜", items: ["🍜", "🥚", "🍥", "🥬", "🍖", "🌽", "🍄", "🍤", "🫑", "🥟"] }
];

// identical difficulty formulas to the old runtime table
function levelCfg(level) {
  const qtyMax = Math.min(10, 2 + Math.floor((level - 1) / 5));
  return {
    menuItems: Math.min(10, 2 + Math.floor((level - 1) / 3)),
    target: Math.round(10 + (level - 1) * 35 / 49),
    patience: Math.max(30, Math.round(70 - (level - 1) * 40 / 49)),
    beltSpeed: Math.round(125 + (level - 1) * 90 / 49),
    refillMs: Math.round(2600 - (level - 1) * 800 / 49),
    maxOnBelt: Math.min(20, qtyMax * 2 + 2),
    qtyMax
  };
}

// mulberry32 — small, deterministic
function mulberry32(seed) {
  let a = seed >>> 0;
  return function () {
    a |= 0; a = (a + 0x6D2B79F5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

function buildRoster(level, total, rng) {
  const cfg = levelCfg(level);
  const menu = THEMES[(level - 1) % THEMES.length].items.slice(0, cfg.menuItems);
  const roster = [];
  for (let i = 0; i < total; i++) {
    roster.push([menu[Math.floor(rng() * menu.length)], 1 + Math.floor(rng() * cfg.qtyMax)]);
  }
  return roster;
}

const levels = [];
for (let level = 1; level <= 50; level++) {
  const cfg = levelCfg(level);
  const rng = mulberry32(20250501 + level * 7919); // fixed per level
  const roster = buildRoster(level, cfg.target + 2, rng);
  // every level's deck must be able to fill the 4 kitchen lines (5 each) at startup
  let total = roster.reduce((s, [, q]) => s + q, 0);
  let guard = 0;
  while (total < 20 && guard++ < 60) {
    const i = Math.floor(rng() * roster.length);
    if (roster[i][1] < cfg.qtyMax) { roster[i][1]++; total++; }
  }
  levels.push({ ...cfg, roster });
}

const out = "/* Auto-generated by tools/generate-levels.js — do not edit by hand. */\n" +
  "globalThis.BELT_BITE_LEVELS = " + JSON.stringify(levels, null, 1) + ";\n";
fs.writeFileSync(path.join(__dirname, "..", "levels-data.js"), out);
console.log("wrote levels-data.js with", levels.length, "levels");
